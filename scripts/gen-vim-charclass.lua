-- Vim の単語境界 `\<` の判定に使う文字クラス表を、Neovim 自身から生成する。
--
-- 使い方:
--   nvim --clean --headless -l scripts/gen-vim-charclass.lua > crates/gtodo-core/src/vim_class.rs
--
-- `--clean` は必須。`charclass()` はカレントバッファの 'iskeyword' を参照するため、
-- ユーザー設定が混ざると Lua 版の既定の挙動と異なる表になる。
--
-- Vim の分類表(mbyte.c の utf_class)を手で書き写さないのは、Unicode のバージョンや
-- Neovim 側の改訂に追従できず、写し間違いも検出できないため。

local out = {}
local function emit(s)
	table.insert(out, s)
end

-- クラス 2(単語構成文字)でないコードポイントの区間を集める。
-- 未割り当ての領域は Vim では既定でクラス 2 になるため、2 以外の区間の方が少ない。
local ranges = {}
local start = nil
local function flush(last)
	if start then
		table.insert(ranges, { start, last })
		start = nil
	end
end

for cp = 1, 0x10FFFF do
	local is_surrogate = cp >= 0xD800 and cp <= 0xDFFF
	local non_word = false
	if not is_surrogate then
		non_word = vim.fn.charclass(vim.fn.nr2char(cp)) ~= 2
	end
	if non_word then
		if not start then
			start = cp
		end
	elseif not is_surrogate then
		flush(cp - 1)
	end
end
flush(0x10FFFF)

emit("// @generated by scripts/gen-vim-charclass.lua — 手で編集しないこと。")
emit(string.format("// Neovim %s / iskeyword=%s", tostring(vim.version()), vim.o.iskeyword))
emit("")
emit("/// Vim の `charclass()` が 2(単語構成文字)を返す文字か。")
emit("pub(crate) fn is_word_char(c: char) -> bool {")
emit("    let cp = u32::from(c);")
emit("    cp != 0")
emit("        && NON_WORD_RANGES")
emit("            .binary_search_by(|&(lo, hi)| {")
emit("                if hi < cp {")
emit("                    std::cmp::Ordering::Less")
emit("                } else if lo > cp {")
emit("                    std::cmp::Ordering::Greater")
emit("                } else {")
emit("                    std::cmp::Ordering::Equal")
emit("                }")
emit("            })")
emit("            .is_err()")
emit("}")
emit("")
emit("/// Vim の `charclass()` が 2 以外を返すコードポイント (NUL を除く) の閉区間。昇順。")
emit("const NON_WORD_RANGES: &[(u32, u32)] = &[")
for _, r in ipairs(ranges) do
	emit(string.format("    (0x%04X, 0x%04X),", r[1], r[2]))
end
emit("];")

io.stdout:write(table.concat(out, "\n") .. "\n")
